class RMSNorm(nn.Module):
    """Root-mean-square normalization; scales tokens without centering."""

    def __init__(self, dim: int, eps: float = 1e-6):
        super().__init__()
        self.eps = eps
        self.weight = nn.Parameter(torch.ones(dim))

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        dtype = x.dtype
        x = x.float()
        x = x * torch.rsqrt(x.pow(2).mean(-1, keepdim=True) + self.eps)
        return (x.to(dtype)) * self.weight


def precompute_rope(head_dim: int, max_seq_len: int, theta: float):
    inv_freq = 1.0 / (theta ** (torch.arange(0, head_dim, 2).float() / head_dim))
    freqs = torch.outer(torch.arange(max_seq_len).float(), inv_freq)
    emb = torch.cat([freqs, freqs], dim=-1)
    return emb.cos(), emb.sin()


def rotate_half(x: torch.Tensor) -> torch.Tensor:
    x1, x2 = x.chunk(2, dim=-1)
    return torch.cat((-x2, x1), dim=-1)


def apply_rope(x: torch.Tensor, cos: torch.Tensor, sin: torch.Tensor) -> torch.Tensor:
    return x * cos[None, None] + rotate_half(x) * sin[None, None]


class MLA(nn.Module):
    """Multi-head Latent Attention with decoupled RoPE."""

    def __init__(self, cfg: Config):
        super().__init__()
        self.n_head = cfg.n_head
        self.qk_nope = cfg.qk_nope_head_dim
        self.qk_rope = cfg.qk_rope_head_dim
        self.v_head_dim = cfg.v_head_dim
        self.q_head_dim = cfg.qk_nope_head_dim + cfg.qk_rope_head_dim
        self.scale = self.q_head_dim ** -0.5

        # Query: low-rank down-projection -> norm -> up-projection to all heads.
        self.q_a_proj = nn.Linear(cfg.n_embd, cfg.q_lora_rank, bias=False)
        self.q_a_norm = RMSNorm(cfg.q_lora_rank, cfg.norm_eps)
        self.q_b_proj = nn.Linear(cfg.q_lora_rank, self.n_head * self.q_head_dim, bias=False)

        # KV: down-project to [latent | shared rope-key]. Only this latent would be cached.
        self.kv_a_proj = nn.Linear(cfg.n_embd, cfg.kv_lora_rank + cfg.qk_rope_head_dim, bias=False)
        self.kv_a_norm = RMSNorm(cfg.kv_lora_rank, cfg.norm_eps)
        # up-project the latent to per-head [k_nope | v].
        self.kv_b_proj = nn.Linear(
            cfg.kv_lora_rank, self.n_head * (self.qk_nope + self.v_head_dim), bias=False
        )
        self.o_proj = nn.Linear(self.n_head * self.v_head_dim, cfg.n_embd, bias=False)

    def forward(self, x, cos, sin, mask):
        b, t, _ = x.shape

        # ---- queries ----
        q = self.q_b_proj(self.q_a_norm(self.q_a_proj(x)))  # [B, T, nh*q_head_dim]
        q = q.view(b, t, self.n_head, self.q_head_dim).transpose(1, 2)  # [B, nh, T, q_head_dim]
        q_nope, q_rope = q.split([self.qk_nope, self.qk_rope], dim=-1)

        # ---- compressed keys/values ----
        kv = self.kv_a_proj(x)  # [B, T, kv_lora_rank + qk_rope]
        kv_latent, k_rope = kv.split([self.kv_a_norm.weight.numel(), self.qk_rope], dim=-1)
        k_rope = k_rope.view(b, t, 1, self.qk_rope).transpose(1, 2)  # [B, 1, T, qk_rope] (shared)
        kv = self.kv_b_proj(self.kv_a_norm(kv_latent))
        kv = kv.view(b, t, self.n_head, self.qk_nope + self.v_head_dim).transpose(1, 2)
        k_nope, v = kv.split([self.qk_nope, self.v_head_dim], dim=-1)

        # ---- decoupled RoPE on just the rope parts, then assemble full q,k ----
        q_rope = apply_rope(q_rope, cos, sin)
        k_rope = apply_rope(k_rope, cos, sin).expand(b, self.n_head, t, self.qk_rope)
        q = torch.cat([q_nope, q_rope], dim=-1)  # [B, nh, T, q_head_dim]
        k = torch.cat([k_nope, k_rope], dim=-1)

        att = (q @ k.transpose(-2, -1)) * self.scale
        att = att.masked_fill(mask[:t, :t], float("-inf"))
        att = F.softmax(att, dim=-1)
        y = att @ v  # [B, nh, T, v_head_dim]
        y = y.transpose(1, 2).reshape(b, t, self.n_head * self.v_head_dim)
        return self.o_proj(y)


class MLP(nn.Module):
    """A SwiGLU MLP; used both as a dense layer and as a single expert (with a smaller hidden size)."""

    def __init__(self, n_embd: int, intermediate: int):
        super().__init__()
        self.gate_proj = nn.Linear(n_embd, intermediate, bias=False)
        self.up_proj = nn.Linear(n_embd, intermediate, bias=False)
        self.down_proj = nn.Linear(intermediate, n_embd, bias=False)

    def forward(self, x):
        return self.down_proj(F.silu(self.gate_proj(x)) * self.up_proj(x))


class DeepseekMoE(nn.Module):
    """Fine-grained routed experts + a shared always-on expert; sigmoid gating with top-k."""

    def __init__(self, cfg: Config):
        super().__init__()
        self.top_k = cfg.n_experts_per_tok
        self.n_experts = cfg.n_experts
        self.scaling = cfg.routed_scaling_factor
        self.gate = nn.Linear(cfg.n_embd, cfg.n_experts, bias=False)
        self.experts = nn.ModuleList(
            MLP(cfg.n_embd, cfg.moe_intermediate_size) for _ in range(cfg.n_experts)
        )
        self.shared = (
            MLP(cfg.n_embd, cfg.moe_intermediate_size * cfg.n_shared_experts)
            if cfg.n_shared_experts > 0
            else None
        )

    def forward(self, x):
        b, t, c = x.shape
        x = x.reshape(-1, c)
        scores = self.gate(x).sigmoid()  # DeepSeek V3 uses sigmoid (not softmax) gating
        topw, topi = scores.topk(self.top_k, dim=-1)
        topw = topw / (topw.sum(dim=-1, keepdim=True) + 1e-20) * self.scaling
        out = torch.zeros_like(x)
        for e in range(self.n_experts):
            sel = topi == e
            if not sel.any():
                continue
            tok_idx, slot = sel.nonzero(as_tuple=True)
            out[tok_idx] += topw[tok_idx, slot].unsqueeze(-1) * self.experts[e](x[tok_idx])
        if self.shared is not None:
            out = out + self.shared(x)
        return out.reshape(b, t, c)


class Block(nn.Module):
    """Pre-norm block: MLA attention + dense MLP (early layers) or DeepseekMoE (later layers)."""

    def __init__(self, cfg: Config, layer_idx: int):
        super().__init__()
        self.attn_norm = RMSNorm(cfg.n_embd, cfg.norm_eps)
        self.attn = MLA(cfg)
        self.ffn_norm = RMSNorm(cfg.n_embd, cfg.norm_eps)
        # The first `first_k_dense` layers are dense; the rest are MoE.
        if layer_idx < cfg.first_k_dense:
            self.ffn = MLP(cfg.n_embd, cfg.dense_intermediate_size)
        else:
            self.ffn = DeepseekMoE(cfg)

    def forward(self, x, cos, sin, mask):
        x = x + self.attn(self.attn_norm(x), cos, sin, mask)
        x = x + self.ffn(self.ffn_norm(x))
        return x


