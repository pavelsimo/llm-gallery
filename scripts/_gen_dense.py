def main() -> None:
    for s in SPECS:
        s = {**s, **SPEC_OVERRIDES.get(s["slug"], {})}
        if s["family"] == "moe":
            s.setdefault("inter", s["moe_inter"])
            s.setdefault("moe_every", 1)
            s.setdefault("nope_every", 0)
            s.setdefault("window", 0)
            s.setdefault("tiny_window", 0 if s["window"] == 0 else min(16, s["window"]))
            s.setdefault("global_every", 1)
            s.setdefault("global_first", False)
            s.setdefault("attention_gate", False)
            if s["slug"] == "llama4-maverick":
                s["nope_every"] = 4
            elif s["slug"] == "arcee-trinity-large":
                s["attention_gate"] = True
            elif s["slug"] == "mimo-v2-flash":
                s["window"] = 128
                s["tiny_window"] = 16
                s["global_every"] = s["n_layer"] + 1
        elif s["family"] == "mamba":
            if "layer_pattern" not in s:
                # Fallback for generated Mamba variants that predate explicit NemotronH patterns:
                # alternate mixer/FFN layers and keep the old periodic attention cadence visible.
                s["layer_pattern"] = "".join(
                    "*" if (i + 1) % s["attn_every"] == 0 else ("M" if i % 2 == 0 else "E")
                    for i in range(s["n_layer"])
                )
        elif s["family"] == "deltanet":
            s.setdefault("partial_rotary_factor", 0.25)
            s.setdefault("linear_conv_kernel_dim", 4)
        elif s["family"] == "olmo":
            s.setdefault("window", 0)
            s.setdefault("tiny_window", 0 if s["window"] == 0 else min(16, s["window"]))
            s.setdefault("global_every", 1)
        fam = s["family"]
        text = (
            _PREAMBLE.format(
                base=BASES[fam],
                family_desc=FAMILY_DESC[fam],
                ref=FAMILY_REF[fam],
                **s,
            )
            + CONFIG_TEMPLATES[fam].format(**s)
            + BODIES[fam]
        )
        (MODELS / f"{s['module']}.py").write_text(text)
        print(f"wrote llm_gallery/models/{s['module']}.py  ({fam}-style)")


if __name__ == "__main__":
    main()
