MODELS = Path(__file__).resolve().parents[1] / "llm_gallery" / "models"


def body_of(stem: str) -> str:
    """Everything after the ``DEFAULT_PRESET = ...`` line: the shared architecture + __main__."""
    text = (MODELS / f"{stem}.py").read_text()
    i = text.index("\nDEFAULT_PRESET = ")
    j = text.index("\n", i + 1)  # end of the DEFAULT_PRESET line
    return text[j + 1 :].lstrip("\n")


